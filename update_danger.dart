import 'dart:convert';
import 'dart:io';

void main() {
  final files = {
    'id.i18n.json': 'Menghapus akun akan memusnahkan semua data sesi lokal, riwayat resonansi, dan pengaturan secara permanen. Semua koleksi stiker dan koin yang terkumpul juga akan hangus. Tindakan ini nggak bisa dibatalkan.',
    'en.i18n.json': 'Deleting your account will permanently destroy all local session data, resonance history, and settings. All collected stickers and coins will also be forfeited. This action cannot be undone.',
    'th.i18n.json': '????????????????????????????????????????????? ???????????????????? ????????????????????????????? ?????????????????????????????????????????????????? ???????????????????????????????',
    'ja.i18n.json': '?????????????????????????????????????????????????????????????????????????????????????',
    'de.i18n.json': 'Das Löschen deines Kontos vernichtet dauerhaft alle lokalen Sitzungsdaten, den Resonanzverlauf und die Einstellungen. Alle gesammelten Sticker und Münzen verfallen ebenfalls. Diese Aktion kann nicht rückgängig gemacht werden.',
    'tm.i18n.json': 'Deleting your account will permanently destroy all local session data, resonance history, and settings. All collected stickers and Faraan will also be forfeited. This action cannot be undone.'
  };

  final baseDir = 'lib/i18n';

  files.forEach((filename, newText) {
    final file = File(baseDir + '/' + filename);
    if (file.existsSync()) {
      final jsonString = file.readAsStringSync();
      final Map<String, dynamic> data = jsonDecode(jsonString);
      
      data['delete_account_warning'] = newText;
      
      final encoder = JsonEncoder.withIndent('    ');
      file.writeAsStringSync(encoder.convert(data));
      print('Updated ' + filename);
    } else {
      print('File not found: ' + filename);
    }
  });
}
